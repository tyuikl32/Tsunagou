/* ============================================================================
 * 控制台配置（前端侧默认值）—— console.config.js
 * ----------------------------------------------------------------------------
 * 这个文件被 index.html 直接引用，它决定页面「自己是谁」：
 *
 *   · 中间层（`tsunagou web start`）托管页面时，会在**同一个路径**上生成
 *     一份替换品（见 src/tsunagou/console/app.py 的 /console.config.js 路由），
 *     所以下面这些值只在「双击 index.html 直接打开」时生效。
 *   · 中间层生成的那份只会写 baseUrl / mode / poll_ms，不碰界面。
 *
 * 字段：
 *   mode      'demo' 演示模式：本页由 assets/js/mock-backend.js 接管（所有请求由它回答）
 *             'live' 连真后端：请求打到同源的 /api/v1，由中间层转发并补令牌
 *   baseUrl   接口前缀，真后端与中间层都是 /api/v1
 *   poll_ms   各面板自动重拉的间隔（毫秒）；0 或负数 = 不自动重拉
 *
 * 注意一个容易踩的坑：“演示”靠的是**演示后端有没有装上**，不是把页面改成不发请求。
 * behavior.js 自己的 mode:'demo' 意思是“一个请求都不发”，会让页面停在空骨架；
 * 演示后端会把页面设回 live，于是渲染/解包/状态更新与连真后端时是同一条代码路径。
 *
 * 切换方式（任选其一，都不需要改 JS）：
 *   · 演示（推荐，能连项目列表一起看） → `tsunagou web start --demo`，然后打开它打印的地址
 *   · 演示（最轻）                    → 直接双击本目录的 index.html（用的就是下面这份配置）
 *   · 连真后端                        → `tsunagou web start`（默认），打开它打印的地址
 *   · 连某个 daemon                   → 把 TSUNAGOU_CONSOLE_CONFIG 换成自己的值（mode: 'live'）
 * ========================================================================== */

window.TSUNAGOU_CONSOLE_CONFIG = {
    mode: 'demo',
    baseUrl: '/api/v1',
    poll_ms: 5000
};
